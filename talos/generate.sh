#!/usr/bin/env bash
# Generate the Talos secrets bundle and one machine config per node.

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PATCHES="$ROOT/talos/patches"
SECRETS_DIR="$ROOT/talos/secrets"
SECRETS="$SECRETS_DIR/secrets.yaml"
GENERATED="$ROOT/talos/generated"

CLUSTER_NAME="${CLUSTER_NAME:-home}"
CP_IP="${CP_IP:-192.168.178.239}"
# Talos 1.14 serves installer images from the Image Factory, and the schematic
# decides which system extensions are installed. talos/schematic.yaml holds the
# customization behind this ID; csi-driver-nfs needs its nfs-utils extension.
SCHEMATIC_ID="${SCHEMATIC_ID:-1b03b1684045f858942e25dda57c45df1fb8ce3479a790e041395905171a72db}"
TALOS_VERSION="${TALOS_VERSION:-v1.14.4}"
INSTALL_IMAGE="${INSTALL_IMAGE:-factory.talos.dev/metal-installer/${SCHEMATIC_ID}:${TALOS_VERSION}}"
# Single-node layout: no workers are generated by default. Generate their
# configs later with:
#   WORKERS="talos-worker-1 talos-worker-2" make secrets
WORKERS="${WORKERS:-}"

COMMON_ARGS=(
  --with-secrets "$SECRETS"
  --with-docs=false
  --with-examples=false
  --force
)

mkdir -p "$SECRETS_DIR" "$GENERATED"
chmod 700 "$SECRETS_DIR"

if [[ -f "$SECRETS" ]]; then
  echo "Reusing secrets bundle: $SECRETS"
else
  echo "Generating secrets bundle: $SECRETS"
  talosctl gen secrets -o "$SECRETS"
  chmod 600 "$SECRETS"
fi

echo "Generating talos-cp-1 for https://${CP_IP}:6443"
talosctl gen config "$CLUSTER_NAME" "https://${CP_IP}:6443" \
  "${COMMON_ARGS[@]}" \
  --install-image "$INSTALL_IMAGE" \
  --config-patch "@$PATCHES/common.yaml" \
  --config-patch-control-plane "@$PATCHES/controlplane.yaml" \
  --output-types controlplane \
  --output "$GENERATED/talos-cp-1.yaml"

for worker in $WORKERS; do
  patch="$PATCHES/${worker#talos-}.yaml"
  echo "Generating $worker"
  talosctl gen config "$CLUSTER_NAME" "https://${CP_IP}:6443" \
    "${COMMON_ARGS[@]}" \
    --install-image "$INSTALL_IMAGE" \
    --config-patch "@$PATCHES/common.yaml" \
    --config-patch-worker "@$patch" \
    --output-types worker \
    --output "$GENERATED/$worker.yaml"
done

talosctl gen config "$CLUSTER_NAME" "https://${CP_IP}:6443" \
  "${COMMON_ARGS[@]}" \
  --output-types talosconfig \
  --output "$GENERATED/talosconfig"

chmod 600 "$GENERATED"/*.yaml "$GENERATED/talosconfig"

# gen config leaves the context without endpoints/nodes, which makes every
# later talosctl call fail with "failed to determine endpoints".
talosctl --talosconfig "$GENERATED/talosconfig" config endpoint "$CP_IP"
talosctl --talosconfig "$GENERATED/talosconfig" config node "$CP_IP"

echo
echo "Generated:"
echo "  $SECRETS"
echo "  $GENERATED/talos-cp-1.yaml"
for worker in $WORKERS; do echo "  $GENERATED/$worker.yaml"; done
echo "  $GENERATED/talosconfig"
echo
echo "Back up $SECRETS to Bitwarden Secrets Manager and the offline recovery kit."
